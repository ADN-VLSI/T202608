module fifo_tb;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // LOCAL PARAMETERS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  localparam int SZ = 3;
  localparam int DW = 16;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // SIGNALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  logic [SZ:0] count_o;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // INTERFACES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  ctrl_if ctrl_intf ();

  data_if #(
      .DATA_WIDTH(DW)
  ) data_in (
      .clk_i  (ctrl_intf.clk),
      .arst_ni(ctrl_intf.arst_n)
  );

  data_if #(
      .DATA_WIDTH(DW)
  ) data_out (
      .clk_i  (ctrl_intf.clk),
      .arst_ni(ctrl_intf.arst_n)
  );

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // DUT
  //////////////////////////////////////////////////////////////////////////////////////////////////

  fifo #(
      .SIZE      (SZ),
      .DATA_WIDTH(DW)
  ) u_dut (
      .clk_i  (ctrl_intf.clk),
      .arst_ni(ctrl_intf.arst_n),

      .data_in_i      (data_in.data),
      .data_in_valid_i(data_in.valid),
      .data_in_ready_o(data_in.ready),

      .data_out_o      (data_out.data),
      .data_out_valid_o(data_out.valid),
      .data_out_ready_i(data_out.ready),

      .count_o(count_o)
  );

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // METHODS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  task automatic apply_reset();
    #100ns;
    data_in.reset(1);
    data_out.reset(0);
    ctrl_intf.apply_reset();
    #100ns;
  endtask

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // PROCEDURALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  initial begin
    logic [DW-1:0] rdata;

    $timeformat(-9, 0, "ns");
    $dumpfile("fifo_tb.vcd");
    $dumpvars(0, fifo_tb);

    ctrl_intf.apply_reset();
    ctrl_intf.start_clock();

    data_in.send('h1234);
    data_out.recv(rdata);

    #100ns;
    $finish;
  end

endmodule
